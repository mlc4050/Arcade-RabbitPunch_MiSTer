"""Generate source lists for the VHDL state shell and its offline evaluation."""
import argparse

from coretools import core_root
from check_state_emu_sources import state_emu_sources


def source_qip(root, boundary, description):
    donors = ['rtl/state/vendor/meatsauce_t80/' + name + '.vhd'
              for name in ('T80_Reg', 'T80_MCode', 'T80_ALU', 'T80')]
    sources = donors + [boundary if name == 'rtl/state/rabbitpunch_state_emu_boundary.vhd' else name
                        for name in state_emu_sources()]
    assert len(sources) == len(set(sources))
    lines = ['# Generated by scripts/create_state_emu_check.py.', '# '+description]
    for name in sources:
        assert (root / name).is_file(), name
        kind = 'VHDL_FILE' if name.endswith('.vhd') else 'SYSTEMVERILOG_FILE'
        lines.append('set_global_assignment -name ' + kind + ' ' + name +
                     (' -library state_t80' if name in donors else ''))
    lines.append('set_global_assignment -name SDC_FILE RabbitPunch.sdc')
    return '\n'.join(lines)+'\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--production', action='store_true',
                        help='generate files.qip only after the actual boundary enables states')
    args = parser.parse_args()
    root = core_root()
    boundary = 'rtl/state/rabbitpunch_state_emu_boundary.vhd'
    evaluation = 'rtl/synth_check/state_emu/state_emu_boundary.vhd'
    original = (root / boundary).read_text()
    disabled = 'GBOOL_ENABLE_STATES => false'
    enabled = 'GBOOL_ENABLE_STATES => true'
    assert original.count(disabled)+original.count(enabled) == 1
    if args.production:
        if enabled not in original:
            parser.error('Production state boundary is still disabled; files.qip was not changed')
        (root/'files.qip').write_text(source_qip(root, boundary,
            'Production VHDL state composition; imported components retain their wrappers.'), newline='\n')
        print('PREPARED production VHDL state source list')
        return
    generated = original.replace(disabled, enabled)
    generated = ('-- Generated by scripts/create_state_emu_check.py.\n'
                 '-- Offline fit only; not a deployable or qualified game revision.\n' + generated)
    (root / evaluation).parent.mkdir(parents=True, exist_ok=True)
    (root / evaluation).write_text(generated, newline='\n')
    (root / 'state_emu_eval.qip').write_text(source_qip(root, evaluation,
        'Offline full-shell fit. Production files.qip is unchanged.'), newline='\n')
    qsf = (root / 'RabbitPunch.qsf').read_text()
    assert qsf.count('source files.qip') == 1
    qsf = '# Offline state-engine evaluation only. Do not deploy.\n' + qsf.replace(
        'source files.qip', 'source state_emu_eval.qip')
    (root / 'RabbitPunch_state_eval.qsf').write_text(qsf, newline='\n')
    (root / 'RabbitPunch_state_eval.qpf').write_text(
        'PROJECT_REVISION = "RabbitPunch_state_eval"\n', newline='\n')
    (root / 'RabbitPunch_state_eval_stp.qsf').write_text(qsf+
        '\n# Preserve instrumented production probe in the VHDL state shell.\n'
        'set_global_assignment -name VERILOG_MACRO "DEBUG_ISSP=1"\n', newline='\n')
    (root / 'RabbitPunch_state_eval_stp.qpf').write_text(
        'PROJECT_REVISION = "RabbitPunch_state_eval_stp"\n', newline='\n')
    print('PREPARED offline full-shell state fit; production sources were not changed')


if __name__ == '__main__':
    main()
