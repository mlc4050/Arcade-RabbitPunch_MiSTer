"""Pin the provisional state image ABI to its complete bit mapping inputs."""
import argparse
import hashlib
import json
from coretools import core_root


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    root = core_root()
    sources = ['rtl/state/'+name+'.vhd' for name in (
        'rabbitpunch_state_layout', 'rabbitpunch_state_body', 'rabbitpunch_state_banks',
        'rabbitpunch_state_memory', 'rabbitpunch_state_machine_backend',
        'rabbitpunch_state_game_timing', 'rabbitpunch_m68k_capture',
        'rabbitpunch_state_fx68k', 'rabbitpunch_t80_capture',
        'rabbitpunch_state_sdram_phase', 'rabbitpunch_state_machine_access')]
    sources += ['rtl/'+name+'.vhd' for name in (
        'rabbitpunch_io', 'rabbitpunch_irq', 'rabbitpunch_audio',
        'rabbitpunch_ym2151', 'rabbitpunch_upd7759', 'rabbitpunch_sound_board',
        'rabbitpunch_read_arbiter', 'rabbitpunch_audio_rom_transport')]
    sources += ['rtl/state/vendor/meatsauce_t80/'+name+'.vhd' for name in (
        'T80', 'T80_Reg', 'T80_ALU', 'T80_MCode')]
    sources += ['rtl/state/vendor/konamigx/gx_ss_m68k.sv']
    models = {}
    for chip, bits in [('jt51', 4016), ('jt7759', 189)]:
        model = root/'rtl/state/generated'/(chip+'_state_netlist.vhd')
        metadata = json.loads(model.with_suffix('.json').read_text())
        digest = hashlib.sha256(model.read_bytes()).hexdigest()
        assert metadata['state_bits'] == bits and metadata['generated_sha256'] == digest
        models[chip] = dict(bits=bits, model_sha256=digest)
    # Text checkout endings do not change an authored mapping. Vendor imports
    # and the generated chip models are admitted byte for byte separately.
    hashes = {}
    for name in sorted(sources):
        data = (root/name).read_bytes()
        if '/vendor/' not in name:
            data = data.replace(b'\r\n', b'\n')
        hashes[name] = hashlib.sha256(data).hexdigest()
    definition = dict(format='RPS1/00400001', abi_revision=1,
        section_bytes=[106496, 96, 32, 64, 504, 24],
        models=models, mapping_sha256=hashes)
    canonical = json.dumps(definition, sort_keys=True, separators=(',', ':')).encode()
    digest = hashlib.sha256(canonical).hexdigest()
    signature = digest[:8].upper()
    package = '''-- SPDX-License-Identifier: GPL-3.0-or-later
-- Copyright (C) 2026 RabbitPunch contributors
-- Generated by scripts/generate_state_abi.py. Provisional until full-game
-- continuation is qualified; previous experimental images are incompatible.
library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

package rabbitpunch_state_abi is
    constant CU32_ABI_SIGNATURE : unsigned(31 downto 0) := x"SIGNATURE";
end package;
'''.replace('SIGNATURE"', signature+'"')
    report = dict(provisional=True, signature_hex=signature,
        definition_sha256=digest, definition=definition,
        scope='Conservative image compatibility identifier. Source correspondence '
              'and section sizes only; no whole-game continuation or FPGA claim.')
    outputs = {'rtl/state/rabbitpunch_state_abi.vhd': package,
               'docs/reference/state_abi.json': json.dumps(report, indent=2)+'\n'}
    for name, content in outputs.items():
        if args.write:
            (root/name).write_text(content, encoding='utf-8', newline='\n')
        else:
            assert (root/name).read_text() == content, 'Regenerate ABI: '+name
    print(('WROTE' if args.write else 'CHECKED')+' provisional state ABI '+signature)


if __name__ == '__main__':
    main()
