"""Prepare the isolated actual-HPS state-control protocol fit."""
from coretools import core_root


def main():
    root = core_root()
    folder = root/'rtl/synth_check/state_host'
    entity = 'state_host_check'
    declarations = (folder/(entity+'.vhd')).read_text().split('    port (\n', 1)[1].split('\n    );', 1)[0]
    ports = {}
    for line in declarations.splitlines():
        name, definition = line.strip().rstrip(';').split(' : ', 1)
        ports[name] = definition
    qsf = ['# Generated by scripts/create_state_host_check.py.',
        'set_global_assignment -name FAMILY "Cyclone V"',
        'set_global_assignment -name DEVICE 5CSEBA6U23I7',
        'set_global_assignment -name TOP_LEVEL_ENTITY '+entity,
        'set_global_assignment -name PROJECT_OUTPUT_DIRECTORY output_files',
        'set_global_assignment -name VHDL_INPUT_VERSION VHDL_2008',
        'set_global_assignment -name NUM_PARALLEL_PROCESSORS 2',
        'set_global_assignment -name SEED 3',
        'set_global_assignment -name SYSTEMVERILOG_FILE ../../../sys/hps_io.sv',
        'set_global_assignment -name VHDL_FILE ../../rabbitpunch_config.vhd',
        'set_global_assignment -name VHDL_FILE ../../state/rabbitpunch_state_config.vhd',
        'set_global_assignment -name VHDL_FILE ../../state/rabbitpunch_state_controls.vhd',
        'set_global_assignment -name VHDL_FILE ../../rabbitpunch_host.vhd',
        'set_global_assignment -name VHDL_FILE '+entity+'.vhd',
        'set_global_assignment -name SDC_FILE '+entity+'.sdc',
        'set_location_assignment PIN_V11 -to i_clk']
    for name, definition in ports.items():
        if name != 'i_clk':
            qsf.append('set_instance_assignment -name VIRTUAL_PIN ON -to '+name+
                       ('[*]' if 'unsigned' in definition else ''))
    (folder/(entity+'.qsf')).write_text('\n'.join(qsf)+'\n', newline='\n')
    (folder/(entity+'.qpf')).write_text('PROJECT_REVISION = "'+entity+'"\n', newline='\n')
    (folder/(entity+'.sdc')).write_bytes((root/'rtl/synth_check/host/host_check.sdc').read_bytes())
    print('PREPARED isolated actual-HPS state control profile; not executed')


if __name__ == '__main__':
    main()
