"""Generate scan-accessible VHDL from the pristine sound chips' mapped JSON.

Only a deliberately small, audited Yosys primitive set is accepted. Unknown
cells, multiple clocks and duplicate state drivers are fatal. Originals stay
unchanged. This generator supplies an evaluation implementation, not proof of
equivalence or Quartus fitness. Freeze gates every sequential state element,
including asynchronous reset assertion, and each word is writable while held.
"""
import argparse
import hashlib
import json
from pathlib import Path
from coretools import core_root


PORTS = {
    'jt7759': dict(rst='i_reset', clk='i_clk', cen='i_chip_enable',
                   stn='i_start_n', cs='i_chip_select', mdn='i_standalone_mode',
                   busyn='o_busy_n', wrn='i_write_n', din='iu8_write_data',
                   drqn='o_data_request_n', rom_cs='o_rom_request',
                   rom_addr='ou17_rom_address', rom_data='iu8_rom_data',
                   rom_ok='i_rom_valid', sound='ou9_pcm'),
    'jt51': dict(rst='i_reset', clk='i_clk', cen='i_chip_enable',
                 cen_p1='i_half_chip_enable', cs_n='i_chip_select_n',
                 wr_n='i_write_n', a0='i_data_register', din='iu8_write_data',
                 dout='ou8_status', ct1='o_control1', ct2='o_control2',
                 irq_n='o_interrupt_n', sample='o_sample', left='ou16_left_pcm',
                 right='ou16_right_pcm', xleft='ou16_full_left_pcm',
                 xright='ou16_full_right_pcm'),
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--chip', choices=tuple(PORTS), required=True)
    parser.add_argument('--inventory', type=Path)
    parser.add_argument('--vector-nets', action='store_true',
                        help='Retain the earlier wide resolved-net carrier for comparison')
    parser.add_argument('--group-flops', action='store_true',
                        help='Group same-clock/reset flops by scan word in one VHDL process')
    parser.add_argument('--output-dir', type=Path)
    args = parser.parse_args()
    root = core_root()
    source = args.inventory or root/'debug/state_netlist'/(args.chip+'_gates')/'inventory.json'
    metadata = json.loads(source.read_text())
    assert metadata['chip'] == args.chip and metadata['gates']
    for name, digest in metadata['source_sha256'].items():
        assert hashlib.sha256((root/name).read_bytes()).hexdigest() == digest, name
    netlist_path = source.parent/'netlist.json'
    assert hashlib.sha256(netlist_path.read_bytes()).hexdigest() == metadata['netlist_sha256']
    module = json.loads(netlist_path.read_text())['modules'][args.chip]
    ports, cells = module['ports'], module['cells']
    assert set(ports) == set(PORTS[args.chip]), 'Unexpected chip interface'
    all_bits = {bit for item in module['netnames'].values() for bit in item['bits'] if isinstance(bit, int)}
    all_bits.update(bit for cell in cells.values() for bits in cell['connections'].values()
                    for bit in bits if isinstance(bit, int))
    width = max(all_bits)+1
    vector = f'su{width}_nets'

    def bit(value):
        if isinstance(value, int):
            return f'{vector}({value})' if args.vector_nets else f's_net_{value}'
        return "'"+value.upper()+"'"

    def pin(cell, name):
        values = cell['connections'][name]
        assert len(values) == 1, (cell['type'], name, values)
        return values[0]

    flipflops = [(name, cell) for name, cell in sorted(cells.items()) if 'DFF' in cell['type']]
    q_bits = [pin(cell, 'Q') for _, cell in flipflops]
    assert len(q_bits) == len(set(q_bits)) == metadata['sequential_bits']
    clock = ports['clk']['bits'][0]
    reset_bits = sorted({pin(cell, 'R') for _, cell in flipflops if 'R' in cell['connections']})
    reset_names = {value: f's_state_reset_{index}' for index, value in enumerate(reset_bits)}
    initialization = ['0'] * width
    for item in module['netnames'].values():
        initial = item.get('attributes', {}).get('init')
        if initial is not None:
            assert len(initial) == len(item['bits'])
            for value, initial_bit in zip(item['bits'], reversed(initial)):
                if isinstance(value, int) and initial_bit in '01':
                    initialization[value] = initial_bit
    entity = 'rabbitpunch_'+args.chip+'_state_netlist'
    state_vector = f'su{len(q_bits)}_state'
    lines = ['-- SPDX-License-Identifier: GPL-3.0-or-later',
             '-- Copyright (C) 2026 RabbitPunch contributors',
             '-- Original chip RTL: Jose Tejada Gomez, GPL-3.0-or-later.',
             '-- Generated by scripts/generate_sound_state_vhdl.py; do not edit.',
             '-- Original sources are unchanged. See the adjacent JSON manifest.',
             '-- Evaluation only: normal equivalence, restore and timing require proof.',
             'library ieee;', 'use ieee.std_logic_1164.all;', 'use ieee.numeric_std.all;',
             '', 'entity '+entity+' is', '    port (']
    declarations = []
    for name, port in ports.items():
        size = len(port['bits'])
        assert port['direction'] in ('input', 'output')
        direction = 'in' if port['direction'] == 'input' else 'out'
        data_type = 'std_logic' if size == 1 else f'unsigned({size-1} downto 0)'
        declarations.append(f'        {PORTS[args.chip][name]} : {direction} {data_type}')
    declarations += ['        i_state_hold : in std_logic',
                     '        i_state_write : in std_logic',
                     '        iu16_state_word_address : in unsigned(15 downto 0)',
                     '        iu32_state_write_data : in unsigned(31 downto 0)',
                     '        ou32_state_read_data : out unsigned(31 downto 0)']
    lines += [';\n'.join(declarations), '    );', 'end entity;', '', 'architecture rtl of '+entity+' is']
    if args.vector_nets:
        lines.append(f'    signal {vector} : unsigned({width-1} downto 0) := "'+''.join(reversed(initialization))+'";')
    else:
        state_bits = set(q_bits)
        for value in sorted(all_bits):
            initial = f" := '{initialization[value]}'" if value in state_bits else ''
            lines.append(f"    signal s_net_{value} : std_logic{initial};")
    lines.append(f'    signal {state_vector} : unsigned({len(q_bits)-1} downto 0);')
    for name in reset_names.values():
        lines.append('    signal '+name+' : std_logic;')
    lines += ['    function F_MUX(v_a, v_b, v_select : std_logic) return std_logic is',
              '    begin', "        if (v_select = '0') then", '            return v_a;',
              "        elsif (v_select = '1') then", '            return v_b;',
              '        elsif (v_a = v_b) then', '            return v_a;',
              '        else', "            return 'X';", '        end if;',
              '    end function;', 'begin',
              '    -- Quartus initializes otherwise unspecified FPGA registers to zero.',
              '    -- Explicit source init bits override that policy above. Native tests',
              '    -- must use the same power-up contract; reset alone is insufficient.',
              "    assert (i_state_write /= '1' or i_state_hold = '1')",
              '        report "State netlist write requires freeze" severity failure;']
    for name, port in ports.items():
        for offset, value in enumerate(port['bits']):
            external = PORTS[args.chip][name]+(f'({offset})' if len(port['bits']) > 1 else '')
            lines.append('    '+(bit(value)+' <= '+external if port['direction'] == 'input'
                                else external+' <= '+bit(value))+';')
    for value, name in reset_names.items():
        lines.append(f'    {name} <= {bit(value)} and not i_state_hold;')
    # Keep readback sensitive only to Q, not thousands of intermediate gate
    # events. These are wire aliases and add no sequential hardware state.
    values = [bit(value) for value in reversed(q_bits)]
    lines.append(f'    {state_vector} <=')
    for offset in range(0, len(values), 16):
        lines.append('        '+' & '.join(values[offset:offset+16])+
                     (' &' if offset+16 < len(values) else ';'))
    for name, cell in sorted(cells.items()):
        kind = cell['type']
        if kind == '$scopeinfo' or 'DFF' in kind:
            continue
        output = bit(pin(cell, 'Y'))
        a = bit(pin(cell, 'A'))
        if kind == '$_NOT_':
            expression = 'not '+a
        elif kind in ('$_AND_', '$_OR_', '$_XOR_'):
            expression = a+' '+dict(_AND_='and', _OR_='or', _XOR_='xor')[kind[1:]]+' '+bit(pin(cell, 'B'))
        elif kind == '$_MUX_':
            expression = 'F_MUX('+a+', '+bit(pin(cell, 'B'))+', '+bit(pin(cell, 'S'))+')'
        else:
            raise AssertionError('Unsupported combinational cell: '+kind)
        lines.append(f'    {output} <= {expression};')
    state_map, groups = [], {}
    for index, (name, cell) in enumerate(flipflops):
        kind = cell['type']
        assert pin(cell, 'C') == clock, 'Additional or derived clock: '+name
        assert kind in ('$_DFF_P_', '$_DFF_PP0_', '$_DFF_PP1_'), kind
        q, d = bit(pin(cell, 'Q')), bit(pin(cell, 'D'))
        reset = reset_names.get(pin(cell, 'R')) if 'R' in cell['connections'] else None
        state_map.append(dict(bit=index, cell=name, q=pin(cell, 'Q'), type=kind,
                              reset=pin(cell, 'R') if reset else None,
                              source=cell.get('attributes', {}).get('src')))
        if args.group_flops:
            groups.setdefault((reset, index//32), []).append((index, q, d, kind[-2] if reset else None))
            continue
        sensitivity = 'i_clk'+(', '+reset if reset else '')
        lines += [f'    state_{index} : process({sensitivity})', '    begin']
        if reset:
            lines += [f"        if ({reset} = '1') then", f"            {q} <= '{kind[-2]}';",
                      '        elsif (rising_edge(i_clk)) then']
        else:
            lines += ['        if (rising_edge(i_clk)) then']
        lines += ["            if (i_state_hold = '1') then",
                  f"                if (i_state_write = '1' and iu16_state_word_address = {index//32}) then",
                  f'                    {q} <= iu32_state_write_data({index%32});',
                  '                end if;', '            else', f'                {q} <= {d};',
                  '            end if;', '        end if;', '    end process;']
    for group_index, ((reset, word), members) in enumerate(groups.items()):
        sensitivity = 'i_clk'+(', '+reset if reset else '')
        lines += [f'    state_group_{group_index} : process({sensitivity})', '    begin']
        if reset:
            lines.append(f"        if ({reset} = '1') then")
            lines += [f"            {q} <= '{reset_value}';" for _, q, _, reset_value in members]
            lines.append('        elsif (rising_edge(i_clk)) then')
        else:
            lines.append('        if (rising_edge(i_clk)) then')
        lines += ["            if (i_state_hold = '1') then",
                  f"                if (i_state_write = '1' and iu16_state_word_address = {word}) then"]
        lines += [f'                    {q} <= iu32_state_write_data({index%32});'
                  for index, q, _, _ in members]
        lines += ['                end if;', '            else']
        lines += [f'                {q} <= {d};' for _, q, d, _ in members]
        lines += ['            end if;', '        end if;', '    end process;']
    lines += [f'    state_read : process({state_vector}, iu16_state_word_address)', '    begin',
              "        ou32_state_read_data <= (others => '0');", '        case to_integer(iu16_state_word_address) is']
    for word in range((len(flipflops)+31)//32):
        values = [f'{state_vector}({index})' if index < len(q_bits) else "'0'"
                  for index in range(word*32, word*32+32)]
        lines += [f'            when {word} =>', '                ou32_state_read_data <= '+' & '.join(reversed(values))+';']
    lines += ['            when others => null;', '        end case;', '    end process;', 'end architecture;']
    out = (args.output_dir or root/'rtl/state/generated').resolve()
    assert out.drive.upper() == 'D:', 'Generated output must stay on D:'
    out.mkdir(parents=True, exist_ok=True)
    destination = out/(args.chip+'_state_netlist.vhd')
    destination.write_text('\n'.join(lines)+'\n', encoding='utf-8', newline='\n')
    metadata = dict(chip=args.chip, entity=entity, state_bits=len(flipflops),
                    net_style='vector' if args.vector_nets else 'scalar',
                    state_process_style='grouped_by_scan_word' if args.group_flops else 'individual',
                    state_words=(len(flipflops)+31)//32, yosys=metadata['yosys'],
                    source_sha256=metadata['source_sha256'],
                    lowered_netlist_sha256=metadata['netlist_sha256'],
                    generator_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                    generated_sha256=hashlib.sha256(destination.read_bytes()).hexdigest(),
                    ports=PORTS[args.chip], state=state_map,
                    accepted=False, scope='Generated evaluation only. All reachable mapped '
                    'flops exported, frozen and scan writable, including asynchronous reset '
                    'gating while frozen. Unknown power-up bits initialize to FPGA zero. '
                    'No normal-mode equivalence, continuation or synthesis qualification yet.')
    (out/(args.chip+'_state_netlist.json')).write_text(json.dumps(metadata, indent=2)+'\n', encoding='utf-8')
    print(destination.as_posix(), 'state_bits='+str(len(flipflops)), flush=True)


if __name__ == '__main__':
    main()
