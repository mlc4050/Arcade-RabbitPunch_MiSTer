"""Prepare a whole logical state-machine fit with direct physical SDRAM pins."""
from pathlib import Path
from coretools import core_root
from run_state_machine_backend_tests import state_machine_sources


def main():
    root = core_root()
    source = root/'rtl/state/rabbitpunch_state_machine.vhd'
    ports = source.read_text().split('    port (\n', 1)[1].split('\n    );', 1)[0]
    rows = []
    for declaration in ports.splitlines():
        name, definition = declaration.strip().rstrip(';').split(' : ', 1)
        direction, kind = definition.split(' ', 1)
        rows.append((name, direction, kind.split(' := ', 1)[0]))
    entity = 'state_machine_check'
    lines = ['-- SPDX-License-Identifier: GPL-3.0-or-later',
        '-- Copyright (C) 2026 RabbitPunch contributors',
        '-- Generated by scripts/create_state_machine_check.py.',
        '-- Registered logical I/O; physical SDRAM pins remain direct.',
        'library ieee;', 'use ieee.std_logic_1164.all;', 'use ieee.numeric_std.all;',
        'use work.rabbitpunch_layout.all;', 'use work.rabbitpunch_config.all;',
        '', 'entity '+entity+' is', '    port (', ports, '    );', 'end entity;',
        '', 'architecture evaluation of '+entity+' is']
    boundaries = {}
    for name, direction, kind in rows:
        if name == 'i_clk' or '_sdram_' in name:
            boundaries[name] = name
        else:
            assert direction in ('in', 'out'), name
            prefix = 's_' if kind == 'std_logic' else 'su'+name.split('_', 1)[0][2:]+'_'
            boundaries[name] = prefix+'boundary_'+name
            lines.append('    signal '+boundaries[name]+' : '+kind+';')
    lines += ['begin', '    boundary : process(i_clk)', '    begin',
              '        if (rising_edge(i_clk)) then']
    for name, direction, _ in rows:
        if boundaries[name] != name:
            target, value = (boundaries[name], name) if direction == 'in' else (name, boundaries[name])
            lines.append('            '+target+' <= '+value+';')
    lines += ['        end if;', '    end process;',
              '    machine : entity work.rabbitpunch_state_machine', '        port map (',
              ',\n'.join('            '+name+' => '+boundaries[name] for name, _, _ in rows),
              '        );', 'end architecture;']
    out = root/'rtl/synth_check/state_machine'
    out.mkdir(parents=True, exist_ok=True)
    (out/(entity+'.vhd')).write_text('\n'.join(lines)+'\n', encoding='utf-8', newline='\n')
    qsf = ['# SPDX-License-Identifier: GPL-3.0-or-later',
        '# Copyright (C) 2026 RabbitPunch contributors',
        'set_global_assignment -name FAMILY "Cyclone V"',
        'set_global_assignment -name DEVICE 5CSEBA6U23I7',
        'set_global_assignment -name TOP_LEVEL_ENTITY '+entity,
        'set_global_assignment -name PROJECT_OUTPUT_DIRECTORY output_files',
        'set_global_assignment -name VHDL_INPUT_VERSION VHDL_2008',
        'set_global_assignment -name NUM_PARALLEL_PROCESSORS 2',
        'set_global_assignment -name SEED 3',
        'set_global_assignment -name SEARCH_PATH ../../..']
    state_t80 = ['rtl/state/vendor/meatsauce_t80/'+name+'.vhd'
                 for name in ('T80_Reg', 'T80_MCode', 'T80_ALU', 'T80')]
    sources = state_t80+[name for name in state_machine_sources() if name.startswith('rtl/')]
    assert len(sources) == len(set(sources))
    for name in sources:
        kind = 'VHDL_FILE' if name.endswith('.vhd') else 'SYSTEMVERILOG_FILE'
        qsf.append('set_global_assignment -name '+kind+' ../../'+name.removeprefix('rtl/')+
                   (' -library state_t80' if name in state_t80 else ''))
    qsf += ['set_global_assignment -name VHDL_FILE '+entity+'.vhd',
            'set_global_assignment -name SDC_FILE '+entity+'.sdc',
            'set_location_assignment PIN_V11 -to i_clk']
    for name, _, kind in rows:
        if name != 'i_clk':
            qsf.append('set_instance_assignment -name VIRTUAL_PIN ON -to '+name+
                       ('[*]' if kind != 'std_logic' else ''))
    (out/(entity+'.qsf')).write_text('\n'.join(qsf)+'\n', encoding='utf-8', newline='\n')
    (out/(entity+'.qpf')).write_text('PROJECT_REVISION = "'+entity+'"\n', encoding='utf-8', newline='\n')
    (out/(entity+'.sdc')).write_bytes((root/'rtl/synth_check/machine/machine_check.sdc').read_bytes())
    print(out.as_posix())


if __name__ == '__main__':
    main()
